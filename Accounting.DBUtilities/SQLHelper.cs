        public static object DeserializeDataObject(object obj, DataTable dt, DataRow dr)
        {
            try
            {
                PropertyInfo[] propertyInfos = obj.GetType().GetProperties();
                foreach (DataColumn column in dt.Columns)
                {
                    foreach (var property in propertyInfos)
                    {
                        if (property.Name.ToLower().Trim() == column.ColumnName.Replace(" ", "").ToLower().Trim())
                        {
                            if (dr[column.ColumnName] != DBNull.Value && !string.IsNullOrEmpty(Convert.ToString(dr[column.ColumnName])))
                                property.SetValue(obj, dr[column.ColumnName]);
                            break;
                        }
                    }
                }
            }
            catch (Exception ex)
            {
                throw;
            }
            return obj;
        }
